def format_block(role: str, depth: str) -> str:
    return _FORMATS[(normalize_role(role), normalize_depth(depth))]


def length_rule(depth: str) -> str:
    if normalize_depth(depth) == "deep":
        return ("- Отвечай развёрнуто, но по существу и без воды: в каждом разделе 2–6 пунктов; "
                "в первой строке ответа всё равно давай прямой вывод")
    return "- Отвечай по существу: до 6 коротких абзацев или пунктов"


