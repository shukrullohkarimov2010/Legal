def parse_subqueries(data, base: str = "", limit: int = 4) -> list:
    """Подвопросы из разобранного ответа модели: только чистые русские строки."""
    raw = (data or {}).get("queries") if isinstance(data, dict) else None
    result = []
    for item in raw if isinstance(raw, list) else []:
        text = re.sub(r"\s+", " ", str(item or "")).strip(" .,-•*")[:120]
        if not text or _TG_LETTERS_RE.search(text) or not _CYRILLIC_RE.search(text):
            continue
        if text.lower() == (base or "").strip().lower() or text.lower() in [r.lower() for r in result]:
            continue
        result.append(text)
        if len(result) >= limit:
            break
    return result


