def previous_document(history) -> str:
    """Последний ответ ассистента, если это составленный документ, иначе «».

    Промпт обычно режет реплики истории по 600–1200 символов, а для правки
    документа нужен весь текст, поэтому берём его отдельно и целиком.
    """
    for item in reversed(history or []):
        if item.get("role") != "ai":
            continue
        content = (item.get("content") or "").strip()
        if len(content) >= _PREVIOUS_DOC_MIN and _DOC_HEAD_RE.search(content[:_DOC_HEAD_WINDOW]):
            return content[:PREVIOUS_DOC_MAX_CHARS]
        return ""  # смотрим только на самый последний ответ ассистента
    return ""


def _detect_kind(text: str):
    for kind, label, pattern in _DOC_KINDS:
        if pattern.search(text):
            return kind, label
    return None


def detect_subtype(text: str) -> str:
    for name, pattern in _SUBTYPES:
        if pattern.search(text):
            return name
    return ""


def detect_document(message: str, translated: str = "", prev_doc: str = "") -> Optional[DocRequest]:
    """Просят составить документ (или поправить только что составленный)?

    `translated` — русский перевод таджикского вопроса: детектор смотрит и на
    оригинал, и на перевод, потому что машинный перевод может потерять слово.
    """
    texts = [t for t in (message, translated) if t and t.strip()]
    if not texts:
        return None
    joined = " ".join(texts)

    # Правка уже составленного документа: «добавь пункт о неустойке».
    # Вопрос («можно ли добавить пункт?») остаётся консультацией.
    if (prev_doc and _EDIT_RE.search(joined) and len(message) < 800
            and not message.rstrip().endswith("?")):
        found = _detect_kind(prev_doc[:_DOC_HEAD_WINDOW]) or ("contract", "договор")
        return DocRequest(found[0], found[1], detect_subtype(prev_doc[:_DOC_HEAD_WINDOW]), edit=True)

    if not _CREATE_RE.search(joined):
        return None
    # Длинное сообщение с вставленным текстом — это разбор, а не заказ.
    if len(message) > 1500:
        return None
    kind = _detect_kind(joined)
    if not kind:
        return None
    if _ANALYSIS_RE.search(joined) and not re.search(
            r"\b(?:составь\w*|составить|напиш\w+|подготов\w+|образец|шаблон\w*)\s+(?:мне\s+)?"
            r"(?:(?!анализ|проверк|разбор|оценк)\w+\s+){0,2}(?:договор|соглашени|заявлени|иск|претензи|жалоб|доверенност|расписк)", joined, re.I):
        return None
    return DocRequest(kind[0], kind[1], detect_subtype(joined) if kind[0] == "contract" else "", edit=False)


