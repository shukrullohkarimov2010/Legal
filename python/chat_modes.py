# Слабая модель нет-нет да пишет служебные слова из промпта. Правило в промпте
# есть (USER_LANGUAGE), а это страховка: оставшееся заменяется кодом, в потоке,
# до показа и до перевода на таджикский. Функция идемпотентна.
_FRAGMENT_RE = re.compile(
    r"(?<![А-Яа-яЁё])(по|в|во|из)\s+(?:приведённых|приведенных|представленных|найденных|переданных|указанных)?\s*"
    r"фрагмент\w*(?:\s+ниже)?", re.I)
_FRAGMENT_FORMS = {"по": "по найденным нормам", "в": "в найденных нормах", "во": "в найденных нормах",
                   "из": "из найденных норм"}


def _fragment_phrase(match):
    word = match.group(1)
    form = _FRAGMENT_FORMS[word.lower()]
    return form[0].upper() + form[1:] if word[0].isupper() else form


_HUMANIZE = [
    (re.compile(r"Точная\s+ссылка\s+не\s+подтверждена\s+RAG\.?", re.I), "Точная статья в нашей базе законов не найдена."),
    (re.compile(r"в\s+подборке\s+норм(?:\s+этого\s+нет)?", re.I), "в нашей базе законов этого нет"),
    (_FRAGMENT_RE, _fragment_phrase),
]


def humanize(text: str) -> str:
    """Заменяет служебные слова промпта на понятные пользователю."""
    if not text:
        return text
    for pattern, replacement in _HUMANIZE:
        text = pattern.sub(replacement, text)
    return text
