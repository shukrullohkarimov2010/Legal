def _code_near(text: str, start: int, end: int) -> Optional[str]:
    """Кодекс, к которому относится ссылка на статью: ближайшее название в той же строке."""
    line_start = text.rfind("\n", 0, start) + 1
    before = text[max(line_start, start - _BEFORE_WINDOW):start]
    best, best_end = None, -1
    for short, pattern in _CODE_RES:
        for match in pattern.finditer(before):
            if match.end() > best_end:
                best, best_end = short, match.end()
    if best:
        return best
    line_end = text.find("\n", end)
    stop = end + _AFTER_WINDOW if line_end < 0 else min(line_end, end + _AFTER_WINDOW)
    after = text[end:stop]
    best, best_start = None, None
    for short, pattern in _CODE_RES:
        match = pattern.search(after)
        if match and (best_start is None or match.start() < best_start):
            best, best_start = short, match.start()
    return best


def misattributed_citations(text: str, results) -> list:
    """Ссылки на статью, приписанные не тому кодексу.

    Проверка номеров сверяет только цифру: «ст. 39 ГК РТ» проходила, если
    статья 39 нашлась в ТК. Здесь пара «кодекс + номер» сверяется с найденными
    фрагментами. Помечается только явная путаница: названный кодекс статьи с
    таким номером не давал, а другой кодекс давал. Остальное (нет такой статьи
    вовсе) ловит проверка номеров.
    """
    pairs, by_article, names = set(), {}, {}
    for item in results or []:
        code, article = item.get("code_short"), str(item.get("article") or "").strip()
        if code and article:
            pairs.add((code, article))
            by_article.setdefault(article, set()).add(code)
            names[code] = item.get("code") or CODE_FULL_NAMES.get(code, code)
    problems = []
    for match in _CITE_RE.finditer(text or ""):
        article = match.group(1)
        code = _code_near(text, match.start(), match.end())
        if not code or (code, article) in pairs or article not in by_article:
            continue
        def full(short):
            return names.get(short) or CODE_FULL_NAMES.get(short, short)

        note = "статья %s указана как статья кодекса «%s», а такая статья найдена в: %s" % (
            article, full(code), ", ".join(full(c) for c in sorted(by_article[article])))
        if note not in problems:
            problems.append(note)
    return problems


_QUOTE_RE = re.compile(r"«([^«»]{15,400})»")
_CITED_LINE_RE = re.compile(r"ст\.|стать[а-яё]*", re.I)


def _norm(text: str) -> str:
    text = (text or "").lower().replace("ё", "е")
    return " ".join(re.sub(r"[^0-9a-zа-я]+", " ", text).split())


def unverified_quotes(text: str, fragments, *known_texts: str) -> list:
    """Цитаты в «ёлочках», которых нет дословно в найденных статьях.

    Проверяются только цитаты в строках со ссылкой на статью: слова, взятые из
    вопроса пользователя («зарплата за три месяца»), и собственные обороты
    модели цитатами закона не считаются. Многоточие внутри цитаты делит её на
    части, каждая из которых должна найтись сама.
    """
    haystack = " " + " ".join(_norm(f) for f in list(fragments or []) + list(known_texts)) + " "
    bad = []
    for match in _QUOTE_RE.finditer(text or ""):
        line_start = text.rfind("\n", 0, match.start()) + 1
        line_end = text.find("\n", match.end())
        line = text[line_start:len(text) if line_end < 0 else line_end]
        if not _CITED_LINE_RE.search(line):
            continue
        parts = [_norm(p) for p in re.split(r"…|\.\.\.", match.group(1))]
        parts = [p for p in parts if len(p.split()) >= 3]
        if parts and not all((" " + p + " ") in haystack for p in parts):
            quote = match.group(1).strip()
            if quote not in bad:
                bad.append(quote)
    return bad


