from dataclasses import dataclass
from typing import Optional

ROLES = ("lawyer", "advocate")
DEPTHS = ("fast", "deep")
DEFAULT_ROLE = "lawyer"
DEFAULT_DEPTH = "fast"


def normalize_role(value) -> str:
    value = str(value or "").strip().lower()
    return value if value in ROLES else DEFAULT_ROLE


def normalize_depth(value) -> str:
    value = str(value or "").strip().lower()
    return value if value in DEPTHS else DEFAULT_DEPTH


# ---------------------------------------------------------------- глубина

@dataclass(frozen=True)
class DepthProfile:
    depth: str
    top_k: int              # сколько статей достаём из кодексов
    max_chars: int          # бюджет символов на RAG-контекст в промпте
    max_tokens: int         # предел ответа на вопрос
    doc_tokens: int         # предел ответа, когда просят составить документ
    history_turns: int      # сколько последних реплик помнит модель
    history_chars: int      # сколько символов реплики уходит в промпт
    subqueries: bool        # разбивать сложную ситуацию на подвопросы для поиска
    reasoning_effort: Optional[str]   # None — оставить значение по умолчанию
    openai_model: Optional[str]       # None — общая модель OPENAI_MODEL


def strong_model() -> Optional[str]:
    """Более сильная модель OpenAI для глубины и документов (GPT_MODEL_DEEP в .env)."""
    return os.environ.get("GPT_MODEL_DEEP") or None


def strong_effort() -> Optional[str]:
    return os.environ.get("CHAT_DEEP_REASONING", "low") or None


def depth_profile(depth: str, base_top_k: int, base_chars: int, base_tokens: int) -> DepthProfile:
    """Профиль генерации.

    «Скорость» — это ровно те значения, которые пользователь настроил в .env
    (CHAT_RAG_TOP_K, CHAT_RAG_MAX_CHARS, CHAT_MAX_TOKENS): режим по умолчанию
    работает как раньше. «Глубина» берёт с запасом от них же, но не меньше
    абсолютного минимума, чтобы урезанный .env не обесценил режим.
    """
    depth = normalize_depth(depth)
    if depth == "deep":
        return DepthProfile(
            depth="deep",
            top_k=max(base_top_k * 2, 10),
            max_chars=max(int(base_chars * 2.5), 14000),
            max_tokens=max(base_tokens * 4, 2600),
            doc_tokens=max(base_tokens * 8, 4200),
            history_turns=8,
            history_chars=1200,
            subqueries=True,
            reasoning_effort=strong_effort(),
            openai_model=strong_model(),
        )
    return DepthProfile(
        depth="fast",
        top_k=base_top_k,
        max_chars=base_chars,
        max_tokens=base_tokens,
        doc_tokens=max(base_tokens * 6, 2600),
        history_turns=4,
        history_chars=600,
        subqueries=False,
        reasoning_effort=None,
        openai_model=None,
    )


