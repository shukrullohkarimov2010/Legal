"""Режимы чата: роль (юрист / адвокат), глубина (скорость / глубина) и документы.

Модуль не ходит ни в модель, ни в RAG: только чистые функции, которые
собирают части промпта и решают, что за запрос пришёл. Благодаря этому его
можно проверить тестами без сервера, а `app.py` остаётся склейкой.

Правила цитирования (только «ПРОВЕРЕННАЯ ССЫЛКА RAG», без выдуманных статей)
живут в `app.py` рядом с подбором фрагментов; здесь их нет намеренно, чтобы
они не расходились в двух местах.
"""

from __future__ import annotations

import os
