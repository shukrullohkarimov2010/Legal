_COMPILED = [dict(topic, regex=re.compile(topic["pattern"], re.I)) for topic in TOPICS]


def is_labor_text(text: str) -> bool:
    """Трудовой ли договор: работодатель и работник упоминаются несколько раз."""
    return len(LABOR_MARKERS.findall(text or "")) >= 3


def match_topics(text: str, contract_type: Optional[str] = None, labor: Optional[bool] = None) -> List[dict]:
    """Темы, признаки которых есть в тексте, в порядке таблицы."""
    if labor is None:
        labor = is_labor_text(text)
    found = []
    for topic in _COMPILED:
        want_labor = topic["labor"]
        if want_labor is not None and want_labor != labor:
            continue
        types = topic.get("types")
        if types and contract_type not in types:
            continue
        if topic["regex"].search(text or ""):
            found.append(topic)
    return found


def topic_results(text: str, search: Callable[[str, int], Iterable[dict]], contract_type: Optional[str] = None,
                  per_topic: int = 2, max_topics: int = 14, labor: Optional[bool] = None) -> List[dict]:
    """Статьи по совпавшим темам. search(query, top_k) — поиск по общему индексу кодексов."""
    seen: Set[tuple] = set()
    picked: List[dict] = []
    for topic in match_topics(text, contract_type, labor)[:max_topics]:
        taken = 0
        limit = topic.get("per_topic", per_topic)
        for item in search(topic["query"], 14):
            if taken >= limit:
                break
            if item.get("code_short") not in topic["codes"]:
                continue
            key = (item.get("code_short"), item.get("article"), item.get("title"))
            if key in seen:
                continue
            seen.add(key)
            picked.append(dict(item, _topic=topic["name"]))
            taken += 1
    return picked
